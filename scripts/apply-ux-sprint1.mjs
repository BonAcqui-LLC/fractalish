function projectBrief(filePath) {
  const item = PROJECT_BRIEFS[routeKey(filePath)];
  if (!item) return "";
  const [question, approach, status, evidence, open] = item;
  return `<section class="section project-orientation" aria-label="Project orientation"><dl class="project-brief"><div><dt>Question</dt><dd>${question}</dd></div><div><dt>Current approach</dt><dd>${approach}</dd></div><div><dt>Status</dt><dd>${status}</dd></div><div><dt>Evidence</dt><dd>${evidence}</dd></div><div><dt>Open problem</dt><dd>${open}</dd></div></dl></section>`;
}

function walk(dir, out = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ent.name === "node_modules" || ent.name === ".git" || ent.name === "_partials" || ent.name === "live-verification") continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, out);
    else if (ent.name.endsWith(".html")) out.push(p);
  }
  return out;
}

function webPath(filePath) {
  let rel = path.relative(ROOT, filePath).split(path.sep).join("/");
  if (rel.endsWith("/index.html")) rel = rel.slice(0, -"/index.html".length) + "/";
  else if (rel === "index.html") rel = "/";
  return "/" + rel.replace(/^\//, "");
}

function headerFor(filePath) {
  const wp = webPath(filePath).toLowerCase();
  let currentHref = null;
  for (const m of NAV_MATCHERS) {
    if (m.test.test(wp)) {
      currentHref = m.href;
      break;
    }
  }
  // Home: brand only, no aria-current on Start Here etc.
  let h = HEADER;
  if (currentHref) {
    const re = new RegExp(
      `(<a )(href="${currentHref.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}")`,
      "i"
    );
    h = h.replace(re, '$1aria-current="page" $2');
  }
  return h;
}

function ensureAssets(html) {
  let out = html;
  if (!/document\.documentElement\.classList\.add\(["']js["']\)/.test(out) && /<\/head>/i.test(out)) {
    out = out.replace(
      /<\/head>/i,
      '  <script>document.documentElement.classList.add("js");</script>\n</head>'
    );
  }
  out = out.replace(/\s*<link\b[^>]*rel=["']stylesheet["'][^>]*href=["']\/(?:styles\.css|assets\/(?:site|search)\.css)[^"']*["'][^>]*>\s*/gi, "\n");
  out = out.replace(/\s*<script\b[^>]*src=["']\/assets\/site\.js[^"']*["'][^>]*><\/script>\s*/gi, "\n");
  out = out.replace(/<\/head>/i, '  <link rel="stylesheet" href="/assets/site.css?v=canon-collapse-20260912">\n  <script src="/assets/site.js?v=canon-collapse-20260912" defer></script>\n</head>');
  out = out.replace(/https:\/\/fractalish\.com\/assets\/figures\/[^"']+\.svg/gi, "https://fractalish.com/assets/figures/cf-social-card.png");
  return out;
}

function ensureMetadata(html, filePath) {
  if (path.basename(filePath).toLowerCase() === "404.html") return html;
  let out = html;
  const title = out.match(/<title>([\s\S]*?)<\/title>/i)?.[1]?.replace(/<[^>]+>/g, "").trim() || "Fractalish";
  const description = out.match(/<meta\b[^>]*name=["']description["'][^>]*content=["']([^"']+)/i)?.[1] || "Fractalish research record.";
  const canonical = out.match(/<link\b[^>]*rel=["']canonical["'][^>]*href=["']([^"']+)/i)?.[1] || `https://fractalish.com${routeKey(filePath)}`;
  const additions = [];
  if (!/property=["']og:title["']/i.test(out)) additions.push(`<meta property="og:title" content="${title}">`);
  if (!/property=["']og:description["']/i.test(out)) additions.push(`<meta property="og:description" content="${description}">`);
  if (!/property=["']og:type["']/i.test(out)) additions.push('<meta property="og:type" content="article">');
  if (!/property=["']og:url["']/i.test(out)) additions.push(`<meta property="og:url" content="${canonical}">`);
  if (!/property=["']og:image["']/i.test(out)) additions.push('<meta property="og:image" content="https://fractalish.com/assets/figures/cf-social-card.png">');
  if (!/name=["']twitter:card["']/i.test(out)) additions.push('<meta name="twitter:card" content="summary_large_image">');
  if (!/name=["']twitter:title["']/i.test(out)) additions.push(`<meta name="twitter:title" content="${title}">`);
  if (!/name=["']twitter:description["']/i.test(out)) additions.push(`<meta name="twitter:description" content="${description}">`);
  if (!/name=["']twitter:image["']/i.test(out)) additions.push('<meta name="twitter:image" content="https://fractalish.com/assets/figures/cf-social-card.png">');
  if (additions.length) out = out.replace(/<\/head>/i, `  ${additions.join("\n  ")}\n</head>`);
  return out;
}

function applyClassification(html, pageClass) {
  const existingMeta = html.match(/<meta\b[^>]*name=["']fractalish:page-class["'][^>]*content=["']([^"']+)["']/i)?.[1];
  const existingBody = html.match(/<body\b[^>]*data-page-class=["']([^"']+)["']/i)?.[1];
  if (existingMeta === pageClass && existingBody === pageClass) return html;
  let out = html.replace(/\s*<meta\b[^>]*name=["']fractalish:page-class["'][^>]*>\s*/gi, "\n");
  out = out.replace(/<\/head>/i, `  <meta name="fractalish:page-class" content="${pageClass}">\n</head>`);
  out = out.replace(/<body\b([^>]*)>/i, (match, attrs) => {
    const clean = attrs.replace(/\sdata-page-class=["'][^"']*["']/i, "");
    return `<body${clean} data-page-class="${pageClass}">`;
  });
  if (pageClass === "ADMIN/UTILITY" && !/name=["']robots["'][^>]*noindex/i.test(out)) {
    out = out.replace(/<\/head>/i, '  <meta name="robots" content="noindex, nofollow">\n</head>');
  }
  return out;
}

function applyCanonCopy(html, filePath) {
  const route = routeKey(filePath);
  let out = html;
  if (route === "/what-cf-does-not-claim" && !out.includes("See what established neighboring fields already explain")) {
    out = out.replace(
      '<p class="lead">Removing a category for inspection is not the same as disproving it.</p>',
      '<p class="lead">Removing a category for inspection is not the same as disproving it.</p><p><a class="text-link" href="/scientific-neighbors">See what established neighboring fields already explain</a></p>'
    );
  }
  if (route === "/project-map") {
    for (const question of [
      "How does bounded process become measurable form?",
      "How should unresolved consequential state persist?",
      "Can formed knowledge move with fidelity?",
      "Can machines witness and use their physical formation?",
      "What hidden formation sits inside the problem?",
    ]) {
      out = out.replace(`<p class="eyebrow">${question}</p>`, `<p class="eyebrow">Question: ${question}</p>`);
    }
  }
  return out;
}

function applyChrome(html, filePath) {
  const redirect = /http-equiv=["']refresh["']/i.test(html);
  if (redirect && /name=["']fractalish:page-class["'][^>]*content=["']ADMIN\/UTILITY["']/i.test(html) && /data-page-class=["']ADMIN\/UTILITY["']/i.test(html) && /\/assets\/site\.css\?v=canon-collapse-20260912/i.test(html) && !/(?:nav-groups|site-footer|site-ai-widget|\/styles\.css|\/assets\/search\.css)/i.test(html)) return html;
  const pageClass = classify(filePath, redirect);
  let out = applyClassification(applyCanonCopy(html, filePath), pageClass);
  out = out.replace(/\s*<script\b[^>]*src=["']\/site-ai-widget\.js[^"']*["'][^>]*><\/script>\s*/gi, "\n");
  if (redirect) {
    out = ensureAssets(out);
    out = out.replace(/\s*<a class=["']skip-link["'][\s\S]*?<\/a>\s*/gi, "\n");
    out = out.replace(/<header class="site-header">[\s\S]*?<\/header>\s*/gi, "");
    out = out.replace(/\s*<footer class="site-footer[\s\S]*?<\/footer>\s*/gi, "\n");
    return out;
  }
  out = ensureMetadata(ensureAssets(out), filePath);
  const header = headerFor(filePath);

  // Remove existing primary header(s)
  out = out.replace(/<header class="site-header">[\s\S]*?<\/header>\s*/gi, "");
  out = out.replace(/\s*<a class=["']skip-link["'][\s\S]*?<\/a>\s*/gi, "\n");
  out = out.replace(/\s*<aside class=["'][^"']*\bcontext-banner\b[\s\S]*?<\/aside>\s*/gi, "\n");
  out = out.replace(/\s*<section class=["'][^"']*\bproject-orientation\b[\s\S]*?<\/section>\s*/gi, "\n");

  // Remove old dual footers / audit footer-nav
  out = out.replace(/\s*<footer class="site-footer[\s\S]*?<\/footer>\s*/gi, "\n");
  out = out.replace(/<nav class="site-footer-nav"[\s\S]*?<\/nav>\s*/gi, "");

  // Insert header after <body...>
  if (/<body[^>]*>/i.test(out)) {
    out = out.replace(/(<body[^>]*>)/i, `$1\n${header}\n`);
  } else {
    out = header + "\n" + out;
  }

  const banner = contextBanner(pageClass);
  if (banner) out = out.replace(/(<\/header>)/i, `$1\n${banner}`);

  const brief = projectBrief(filePath);
  if (brief) {
    out = out.replace(/(<main\b[^>]*>[\s\S]*?<header\b[^>]*>[\s\S]*?<\/header>)/i, `$1\n${brief}`);
  }

  // Keep a stable main-content landmark target without disturbing existing IDs.
  out = out.replace(/<main(?![^>]*\bid=)([^>]*)>/i, '<main id="main-content"$1>');
  if (!/\bid=["']main-content["']/i.test(out)) {
    out = out.replace(/(<\/header>)/i, '$1\n<span id="main-content" tabindex="-1"></span>');
  }

  // Fill missing canonical metadata on content pages; redirects retain their existing policy.
  if (!redirect && path.basename(filePath).toLowerCase() !== "404.html" && !/<link\b[^>]*rel=["']canonical["']/i.test(out)) {
    const canonical = `https://fractalish.com${webPath(filePath)}`;
    out = out.replace(/<\/head>/i, `  <link rel="canonical" href="${canonical}">\n</head>`);
  }

  // Insert footer before </body>
  if (/<\/body>/i.test(out)) {
    out = out.replace(/<\/body>/i, `\n${FOOTER}\n</body>`);
  } else {
    out = out + "\n" + FOOTER;
  }

  if (CHAT_ROUTES.has(routeKey(filePath))) {
    out = out.replace(/(<footer class="site-footer)/i, '<script src="/site-ai-widget.js" defer data-site-name="Fractalish"></script>\n$1');
  }

  // Avoid double headers if script run twice
  const headerCount = (out.match(/class="site-header"/g) || []).length;
  if (headerCount > 1) {
    // keep first only
    let n = 0;
    out = out.replace(/<header class="site-header">[\s\S]*?<\/header>\s*/gi, (m) => {
      n += 1;
      return n === 1 ? m : "";
    });
  }
  const footerCount = (out.match(/site-footer-unified/g) || []).length;
  if (footerCount > 1) {
    let n = 0;
    out = out.replace(/<footer class="site-footer site-footer-unified">[\s\S]*?<\/footer>\s*/gi, (m) => {
      n += 1;
      return n === 1 ? m : "";
    });
  }

  return out;
}

const files = walk(ROOT);
let changed = 0;
for (const f of files) {
  const before = fs.readFileSync(f, "utf8");
  // Skip pure redirect-only mini pages? still give them chrome if they have body
  if (!/<body/i.test(before) && !/<\/html>/i.test(before)) continue;
  const after = applyChrome(before, f);
  if (after !== before) {
    fs.writeFileSync(f, after, "utf8");
    changed += 1;
    console.log("updated", path.relative(ROOT, f));
  }
}

